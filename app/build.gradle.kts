val localProps = Properties().apply {
    val file = rootProject.file("local.properties")
    if (file.exists()) {
        file.inputStream().use { load(it) }
    }
}

fun getConfigValue(key: String, default: String = ""): String {
    return localProps.getProperty(key)
        ?: System.getenv(key)
        ?: default
}

